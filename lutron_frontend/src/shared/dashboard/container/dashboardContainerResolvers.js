import { buildEnergyWidgetRenderContext } from './widgetSlotResolvers';

export function buildBasicEnergyWidgetRenderContext(orchestration, runtime) {
  const { widgets, dates } = orchestration;
  const {
    widgetList,
    energyConsumption,
    energySavings,
    peakMinConsumption,
    energyConsumptionLoading,
    energySavingsLoading,
    peakMinConsumptionLoading,
    savingsByStrategy,
    totalConsumptionByGroup,
    lightPowerDensity,
    lightingUnit,
    globalLoading,
    selectedDuration,
    currentDate,
    currentYear,
    selectedAreas,
    areaGroups,
    isLargeScreen,
    chartHeaderStyle,
    ChartLoader,
    transformDataForCharts,
    energyLineChartSurface,
    energyMetricLight,
    consumptionExportControl,
    savingsExportControl,
    totalConsumptionByGroupExportControl,
    consumptionBlankPreview,
    showEnergyStandaloneDurationFilter,
    renderEnergyLineChartEmptyExtras,
    ENERGY_LIGHT_FULL_CARD_HEIGHT_PX,
  } = runtime;

  return buildEnergyWidgetRenderContext({
    variant: 'basic',
    titles: widgets.energyWidgetTitles,
    widgetList,
    getWidgetTitle: widgets.getWidgetTitle,
    data: {
      memoizedEnergyConsumption: widgets.memoizedEnergyConsumption,
      memoizedEnergySavings: widgets.memoizedEnergySavings,
      savingsByStrategy,
      totalConsumptionByGroup,
      lightPowerDensity,
      lightingUnit,
      peakMinConsumption,
    },
    loading: {
      energyConsumptionLoading,
      energySavingsLoading,
      peakMinConsumptionLoading,
    },
    chartLoading: widgets.chartLoading,
    allEnergyChartsReady: widgets.allEnergyChartsReady,
    globalLoading,
    colors: { consumption: widgets.consumptionColors, savings: widgets.savingsColors },
    chartHeaderStyle,
    ChartLoader,
    transformDataForCharts,
    selectedDuration,
    currentDate,
    currentYear,
    selectedAreas,
    energyCustomNeedsDates: dates.energyCustomNeedsDates,
    isLargeScreen,
    areaGroups,
    overrides: {
      consumption: {
        chartSurface: energyLineChartSurface,
        exportControl: consumptionExportControl,
        emptyStateExtras:
          !showEnergyStandaloneDurationFilter ? renderEnergyLineChartEmptyExtras?.() : null,
        blankChartPreview: consumptionBlankPreview,
        energyLightFullCardHeightPx: ENERGY_LIGHT_FULL_CARD_HEIGHT_PX,
      },
      savings: {
        chartSurface: energyLineChartSurface,
        exportControl: savingsExportControl,
        blankChartPreview: consumptionBlankPreview,
        energyLightFullCardHeightPx: ENERGY_LIGHT_FULL_CARD_HEIGHT_PX,
      },
      savings_by_strategy: {
        chartSurface: energyLineChartSurface,
        energyLightFullCardHeightPx: ENERGY_LIGHT_FULL_CARD_HEIGHT_PX,
      },
      total_consumption_by_group: {
        chartSurface: energyLineChartSurface,
        energyLightFullCardHeightPx: ENERGY_LIGHT_FULL_CARD_HEIGHT_PX,
        exportControl: totalConsumptionByGroupExportControl,
      },
      light_power_density: { chartSurface: energyMetricLight ? 'light' : 'dark' },
      peak_and_minimum_consumption: { chartSurface: energyLineChartSurface },
    },
  });
}


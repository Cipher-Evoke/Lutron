export function buildCustomizedEnergyWidgetRenderContext(orchestration, runtime) {
  const { widgets, dates } = orchestration;
  return buildEnergyWidgetRenderContext({
    variant: 'customized',
    titles: widgets.energyWidgetTitles,
    widgetList: runtime.widgetList,
    getWidgetTitle: widgets.getWidgetTitle,
    data: runtime.widgetContextData || {},
    loading: runtime.widgetContextLoading || {},
    chartLoading: widgets.chartLoading,
    allEnergyChartsReady: widgets.allEnergyChartsReady,
    globalLoading: runtime.globalLoading,
    colors: { consumption: widgets.consumptionColors, savings: widgets.savingsColors },
    chartHeaderStyle: runtime.chartHeaderStyle,
    ChartLoader: runtime.ChartLoader,
    transformDataForCharts: runtime.transformDataForCharts,
    selectedDuration: runtime.selectedDuration,
    currentDate: runtime.currentDate,
    currentYear: runtime.currentYear,
    selectedAreas: runtime.selectedAreas,
    energyCustomNeedsDates: dates.energyCustomNeedsDates,
    isLargeScreen: runtime.isLargeScreen,
    areaGroups: runtime.areaGroups,
    areaIdToDisplayName: runtime.areaIdToDisplayName,
    overrides: runtime.widgetContextOverrides || {},
  });
}
